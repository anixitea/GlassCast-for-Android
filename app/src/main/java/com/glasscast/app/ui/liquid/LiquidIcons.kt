    private fun glyph(name: String, vararg paths: Pair<String, Boolean>): ImageVector =
        ImageVector.Builder(
            name = name,
            defaultWidth = 24.dp,
            defaultHeight = 24.dp,
            viewportWidth = 24f,
            viewportHeight = 24f
        ).apply {
            paths.forEach { (data, evenOdd) ->
                addPath(
                    pathData = addPathNodes(data),
                    pathFillType = if (evenOdd) PathFillType.EvenOdd else PathFillType.NonZero,
                    fill = SolidColor(Color.Black)
                )
            }
        }.build()
}
