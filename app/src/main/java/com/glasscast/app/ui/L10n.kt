package com.glasscast.app.ui

import java.util.Locale

/**
 * Interface text in the phone's language — Korean, German, Spanish and Dutch,
 * English otherwise. There is no setting: it follows the system language.
 *
 * `tr("Library")` looks the English up in the language's table; {0}, {1} take
 * the arguments, so each language can put numbers and names where its grammar
 * wants them ("{0} unplayed" is "미재생 {0}개" in Korean). A plain function
 * rather than string resources because much of the text is set outside
 * composition — toasts from click handlers, sync errors, notifications.
 * Anything missing from a table falls back to the English, so a gap is never a
 * crash. When the phone's language changes, Android recreates the activity and
 * every screen reads its text again.
 */
fun tr(en: String, vararg args: Any?): String {
    val table = when (Locale.getDefault().language) {
        "ko" -> L10nTables.ko
        "de" -> L10nTables.de
        "es" -> L10nTables.es
        "nl" -> L10nTables.nl
        else -> null
    }
    var out = table?.get(en) ?: en
    args.forEachIndexed { i, a -> out = out.replace("{$i}", a.toString()) }
    return out
}

